import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(mobileRoot, '..', '..');
const rootManifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const workspacePaths = rootManifest.workspaces;
const manifests = workspacePaths.map((workspace) => ({ workspace, value: JSON.parse(fs.readFileSync(path.join(root, workspace, 'package.json'), 'utf8')) }));
const scriptPath = path.join(root, 'scripts', 'step61-dependency-resolution-preflight.mjs');
const docsPath = path.join(root, 'docs', 'STEP61_DEPENDENCY_RESOLUTION_PREFLIGHT.md');
const script = fs.readFileSync(scriptPath, 'utf8');
const docs = fs.readFileSync(docsPath, 'utf8');
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks += 1; };

check(workspacePaths.length === 3, 'root declares three workspaces');
check(workspacePaths.includes('apps/web'), 'web workspace remains declared');
check(workspacePaths.includes('apps/admin'), 'admin workspace remains declared');
check(workspacePaths.includes('apps/mobile'), 'mobile workspace remains declared');
check(rootManifest.engines.node === '>=22.13.0', 'Node engine floor remains explicit');
check(rootManifest.scripts['preflight:dependencies'] === 'node scripts/step61-dependency-resolution-preflight.mjs', 'dependency preflight command is wired');
check(fs.existsSync(scriptPath), 'dependency preflight script exists');
check(script.includes('package-lock.json is still missing'), 'preflight detects missing root lockfile');
check(script.includes('Do not switch CI to npm ci'), 'preflight protects CI from premature npm ci');
check(manifests.every(({ value }) => value.private === true), 'all workspace packages remain private');
check(manifests.every(({ value }) => Boolean(value.name)), 'all workspace package names exist');
check(manifests.every(({ value }) => Boolean(value.scripts)), 'all workspace scripts maps exist');
const mobile = manifests.find(({ workspace }) => workspace === 'apps/mobile').value;
check(mobile.dependencies.expo === '~58.0.0', 'Expo version range is unchanged');
check(mobile.dependencies['react-native'] === '0.88.0', 'React Native version is unchanged');
check(mobile.dependencies.react === '19.3.0', 'React version is unchanged');
check(fs.existsSync(docsPath), 'Step61 documentation exists');
check(docs.toLowerCase().includes('registry-backed'), 'documentation distinguishes registry resolution from static checks');
const run = spawnSync(process.execPath, [scriptPath], { cwd: root, encoding: 'utf8' });
check(run.status === 2, 'preflight fails closed while lockfile is absent');
check(run.stderr.includes('root package-lock.json is still missing'), 'preflight reports missing lockfile explicitly');
console.log(`Step61 dependency resolution preflight: ${checks}/${checks} checks passed.`);
