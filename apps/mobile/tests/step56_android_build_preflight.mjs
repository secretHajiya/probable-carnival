import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(mobileRoot, '..', '..');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const app = readJson(path.join(mobileRoot, 'app.json')).expo;
const pkg = readJson(path.join(mobileRoot, 'package.json'));
const rootPkg = readJson(path.join(repoRoot, 'package.json'));
const workflow = fs.readFileSync(path.join(repoRoot, 'codemagic.yaml'), 'utf8');
const notes = fs.readFileSync(path.join(mobileRoot, 'ANDROID_BUILD_NOTES.md'), 'utf8');
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks += 1; };

check(app.name === 'Vyra Rewards Global', 'Android display name is set');
check(app.slug === 'vyra-rewards-global', 'Expo slug is stable');
check(app.orientation === 'portrait', 'Portrait orientation is explicit');
check(app.android?.package === 'com.vyra.rewardsglobal', 'Android application ID is set');
check(Number.isInteger(app.android?.versionCode) && app.android.versionCode > 0, 'Android versionCode is positive');
check(app.android.permissions.includes('INTERNET'), 'INTERNET permission exists');
check(app.android.permissions.includes('ACCESS_NETWORK_STATE'), 'ACCESS_NETWORK_STATE permission exists');
check(app.android.permissions.includes('AD_ID'), 'AD_ID permission exists');
check(app.android.softwareKeyboardLayoutMode === 'pan', 'Keyboard pan behavior is configured');
check(app.plugins.includes('expo-secure-store'), 'Secure Store config plugin is included');
check(pkg.dependencies.expo?.startsWith('~58.'), 'Mobile workspace targets Expo SDK 58');
check(pkg.dependencies.react === '19.3.0', 'React version is pinned');
check(pkg.dependencies['react-native'] === '0.88.0', 'React Native version is pinned');
check(pkg.dependencies['expo-secure-store'], 'Secure Store native dependency exists');
check(pkg.dependencies['unity-levelplay-mediation'], 'Unity LevelPlay dependency exists');
check(pkg.scripts['prebuild:android'], 'Android prebuild script exists');
check(pkg.scripts['build:android:release'], 'Android release build script exists');
check(pkg.scripts.typecheck === 'tsc --noEmit', 'Typecheck script exists');
check(rootPkg.workspaces.includes('apps/mobile'), 'Mobile app is part of npm workspaces');
check(rootPkg.scripts['prebuild:mobile:android'], 'Root Android prebuild command exists');
check(rootPkg.scripts['typecheck:mobile'], 'Root mobile typecheck command exists');
check(workflow.includes('node: 22.13.0'), 'Codemagic Node runtime is pinned');
check(workflow.includes('java: 17'), 'Codemagic Java runtime is pinned to 17');
check(workflow.includes('npx expo config --type public'), 'CI validates Expo config');
check(workflow.includes('npx expo prebuild --platform android --non-interactive'), 'CI generates Android native project');
check(workflow.includes('./gradlew assembleRelease'), 'CI builds release APK with bundled JavaScript');
check(workflow.includes('app-release.apk'), 'CI collects release APK artifact');
check(notes.includes('release APK embeds the JavaScript bundle'), 'Debug/release limitation is documented');
check(notes.includes('No generated `android/` directory is committed'), 'Generated native directory policy is documented');
check(!fs.existsSync(path.join(mobileRoot, 'android')), 'No stale generated Android project is committed');
check(!fs.existsSync(path.join(repoRoot, 'node_modules')), 'Preflight does not assume dependencies are installed');
check(!fs.existsSync(path.join(repoRoot, 'package-lock.json')), 'Lockfile absence is detected for CI follow-up');
check(!fs.existsSync(path.join(mobileRoot, 'google-services.json')), 'No untracked Firebase config is assumed');
check(!/service_role|CPX_HASH|LEVELPLAY_S2S_SECRET|PAYPAL_CLIENT_SECRET/i.test(fs.readFileSync(path.join(mobileRoot, '.env.example'), 'utf8')), 'Mobile env example does not contain private server secrets');

const nodeMajor = Number(process.versions.node.split('.')[0]);
const nodeMinor = Number(process.versions.node.split('.')[1]);
check(nodeMajor > 22 || (nodeMajor === 22 && nodeMinor >= 13), 'Current Node runtime meets CI minimum');
console.log(`Step56 Android build preflight: ${checks}/${checks} checks passed`);
console.log('Environment note: this is a source/configuration preflight, not an Expo prebuild, Gradle build, APK, emulator, or device test.');
console.log('CI note: repository has no package-lock.json; generate and commit a lockfile before switching CI from npm install to npm ci.');
